export const MEDICINE_CATEGORIES = [...new Set(BASE.map(b => b[4]))];

export function buildMedicineCatalogue(target = 200) {
  const items = [];
  for (const [generic, form, strengths, unit, cat, cls, cost, minStock] of BASE) {
    for (const s of strengths) {
      items.push({ generic, form, strength: s, unit, cat, cls, cost, minStock });
    }
  }
  // Top up to exactly `target` with pack-size variants of fast movers
  const fast = items.filter(i => ['TABLET', 'CAPSULE'].includes(i.form));
  let k = 0;
  while (items.length < target) {
    const b = fast[k++ % fast.length];
    items.push({ ...b, strength: `${b.strength} (strip isi ${k % 2 ? 10 : 4})`, cost: Math.round(b.cost * 1.1) });
  }
  return items.slice(0, target).map((m, i) => ({
    ...m,
    code: `MED-${String(i + 1).padStart(4, '0')}`,
    name: `${m.generic} ${m.strength === '-' ? '' : m.strength}`.trim(),
  }));
}

